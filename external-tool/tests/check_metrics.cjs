const assert=require('node:assert/strict');
const {wallAxis,wallEnds,balance,density}=require('../dist/factory-metrics.js');
assert.equal(wallAxis(0),90);
assert.equal(wallAxis(Math.PI/2),0);
assert.deepEqual(wallEnds({yaw:0,position:[10,20,0]}),[[10,16],[10,24]]);
const recipe=(inputs,outputs,supported=true)=>({recipe:'test',rateModel:{supported,inputs,outputs}});
const item=(id,rate)=>({id,name:id,rate});
const copper=[recipe([item('ore',120)],[item('ingot',120)]),recipe([item('ingot',120)],[item('sheet',60)])];
assert.equal(balance(copper).score,100);
assert.equal(balance(copper).intermediate.length,1);
assert.equal(balance([copper[0],recipe([item('ingot',60)],[item('sheet',30)])]).score,100);
assert.equal(balance([recipe([],[])]).score,null);
assert.equal(balance([...copper,recipe([],[],false)]).score,null);
assert.equal(balance([recipe([item('ingot',240)],[]),copper[0]]).score,50);
const userExample=[recipe([],[item('ingot',360),item('wire',340)]),recipe([item('ingot',330),item('wire',240)],[])];
assert.equal(balance(userExample).score,100,'Exports must not reduce internal coverage');
const machine=(id,x,y,z=0)=>({id,category:'machine',recipe:'test',position:[x,y,z]});
const group=[machine('a',0,0),machine('b',8,0),machine('c',0,8),machine('d',8,8)];
const second=group.map(b=>({...b,id:b.id+'2',position:[b.position[0]+150,b.position[1],0]}));
const upper=group.map(b=>({...b,id:b.id+'up',position:[...b.position.slice(0,2),30]}));
const scattered=machine('noise',70,70);
const example=[...group,...second,...upper,scattered,{...machine('wall',80,70),category:'wall'},{...machine('miner',0,0),recipe:null}];
const zones=density(example);
assert.equal(zones.length,3);
assert.ok(zones.every(z=>z.machineIds.length===4));
assert.deepEqual(density([...example].reverse()),zones,'Detection must not depend on input order');
assert.deepEqual(density([scattered]),[]);
assert.equal(density([...group,...group.map(b=>({...b,id:b.id+'near',position:[b.position[0]+30,b.position[1],0]}))],36).length,1);
console.log('PASS: wall geometry, coverage including export regression, unavailable scores, density clusters/noise/floors/order/radius');
