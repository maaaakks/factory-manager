const assert=require('node:assert/strict');
const A=require('../dist/workshop-assist.js'),M=require('../dist/workshop-model.js'),data=require('../dist/planner-data.json');
const iron='Desc_OreIron_C',plate='Desc_IronPlateReinforced_C',plain='Desc_IronPlate_C';
const solve=(inputs,outputs)=>A.resolveFlexible({inputs,outputs},data);
const row=(id,rate)=>({id,rate});
let r=solve([row(iron,120)],[row(plate,null)]);
assert.equal(r.outputs[0].rate,10);assert.equal(r.inputs[0].rate,120);
r=solve([row(iron,null)],[row(plate,10)]);assert.equal(r.inputs[0].rate,120);
r=solve([],[row(plate,10)]);assert.equal(r.inputs[0].rate,120);
r=solve([row(iron,150)],[row(plate,10)]);assert.equal(r.unused[0].rate,30);
assert.throws(()=>solve([row(iron,60)],[row(plate,10)]),/insuffisante/);
assert.throws(()=>solve([row(iron,null)],[row(plate,null)]),/débit d’entrée/);
assert.throws(()=>solve([row(iron,120)],[row(iron,null)]),/à la fois/);
r=solve([row(iron,150)],[row(plate,10),row(plain,null)]);assert.equal(r.outputs[1].rate,20);
r=solve([row(iron,150)],[row(plate,null),row(plain,null)]);assert.equal(r.outputs[0].rate,r.outputs[1].rate);assert.ok(Math.abs(r.inputs[0].rate-150)<1e-6);
const p=M.fresh('auto-test');p.flows={inputs:[row(iron,120)],outputs:[row(plate,null)]};assert.equal(M.read(JSON.stringify(p)).flows.outputs[0].rate,null);
for(const rate of [0,-1,'',NaN,Infinity,100001])assert.throws(()=>M.read({...p,flows:{inputs:[],outputs:[row(plate,rate)]}}));
const before=JSON.stringify(p);A.resolveFlexible(p.flows,data);assert.equal(JSON.stringify(p),before);
const placed=A.calculate(solve(p.flows.inputs,p.flows.outputs),data,{size:48});assert.equal(placed.objects.length,14);
console.log('PASS: automatic inputs/outputs, remaining budgets, equal auto shares, errors, persistence, non-mutation and 14-machine handoff');
