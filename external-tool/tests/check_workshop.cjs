const assert=require('node:assert/strict');
const M=require('../dist/workshop-model.js');
const p=M.fresh('test');
const o={id:'smelter',type:'smelter',name:'Fonderie',x:3,y:5,w:6,d:9,rotation:0,z:0,h:6,recipe:null,clock:1};
assert.equal(M.candidate(p,o),null);
p.objects.push(o);
assert.match(M.candidate(p,{...o,id:'clash',x:4}),/chevauche/);
assert.match(M.candidate(p,{...o,id:'outside',x:0}),/dépasse/);
assert.equal(M.candidate(p,{...o,id:'touch',x:9}),null,'Adjacent edges are allowed');
assert.match(M.candidate(p,{...o,rotation:90}),/dépasse/,'Rotation changes physical bounds');
const d=M.duplicate(p,o.id,'copy');assert.ok(d);assert.notEqual(d.id,o.id);assert.equal(M.candidate(p,d),null);
p.objects.push(d);assert.deepEqual(M.read(JSON.stringify(p)),p);
assert.throws(()=>M.read({...p,schemaVersion:99}));
assert.throws(()=>M.read({...p,objects:[o,{...d,id:o.id}]}));
assert.throws(()=>M.read({...p,objects:[{...o,x:NaN}]}));
assert.throws(()=>M.read({...p,objects:[{...o,rotation:45}]}));
assert.equal(M.candidate(p,{...o,w:-1}),'Valeurs invalides');
assert.equal(M.area(p),108);
console.log('PASS: bounds, overlap, touching edges, rotated bounds, duplication, JSON roundtrip and malformed project rejection');
